import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { validateDiagram } from '@swv/core';
import { listFiles, repoRoot } from '@swv/tool-kit';
import { zipSync, type Zippable } from 'fflate';
import { rolldown } from 'rolldown';

import { KIT_NAME, SKILLS, type SkillConfig } from './config.ts';
import { bundledPaths, checkFrontMatter, joinShared, readFrontMatter } from './skill-text.ts';

const here = dirname(fileURLToPath(import.meta.url));
const SOURCES = resolve(repoRoot, 'skills');
/** A fixed time and sorted entries, so the same sources give the same bytes. */
const ZIP_TIME = new Date(2026, 9, 31);

export const DEFAULT_OUT = resolve(repoRoot, 'tools/build-skills/dist');

function zipFiles(files: { name: string; path: string }[]): Uint8Array {
  const entries: Zippable = {};
  const sorted = [...files].sort((a, b) => (a.name < b.name ? -1 : 1));
  for (const { name, path } of sorted) {
    const data = new Uint8Array(readFileSync(path));
    entries[name] = [data, { level: 9, mtime: ZIP_TIME, os: 3, attrs: (0o100644 << 16) >>> 0 }];
  }
  return zipSync(entries);
}

/** Bundles one command-line script, with `@swv/core` inside it, into one file with no imports. */
async function bundleScript(entry: string): Promise<string> {
  const build = await rolldown({ input: resolve(here, entry), platform: 'node', logLevel: 'warn' });
  const { output } = await build.generate({
    format: 'esm',
    banner: '// Generated by tools/build-skills from TypeScript sources. Edit those, not this file.',
  });
  await build.close();
  const [chunk] = output;
  return chunk.code;
}

function checkExamples(skill: SkillConfig, dir: string): void {
  if (!existsSync(dir)) return;
  for (const file of listFiles(dir)) {
    const code = readFileSync(resolve(dir, file), 'utf8');
    const result = validateDiagram(code, { strict: skill.strictExamples });
    const failing = result.issues.filter((i) => skill.strictExamples || i.severity !== 'hint');
    if (failing.length > 0) {
      const lines = failing.map((i) => `  line ${i.line}: ${i.code} ${i.message}`).join('\n');
      throw new Error(`${skill.name}/examples/${file} fails the validator:\n${lines}`);
    }
  }
}

/** Writes one self-contained skill folder and returns the size of its `SKILL.md`. */
function buildSkill(skill: SkillConfig, out: string, validator: string): void {
  const source = resolve(SOURCES, skill.name);
  const shared = resolve(SOURCES, 'shared');
  const text = joinShared(readFileSync(resolve(source, 'SKILL.src.md'), 'utf8'), (file) =>
    readFileSync(resolve(shared, file), 'utf8'),
  );
  const others = SKILLS.filter((other) => other.name !== skill.name);
  checkFrontMatter(readFrontMatter(text), skill, others);

  const target = resolve(out, skill.name);
  mkdirSync(resolve(target, 'scripts'), { recursive: true });
  writeFileSync(resolve(target, 'SKILL.md'), text);
  writeFileSync(resolve(target, 'scripts/validate.mjs'), validator);
  for (const file of skill.references) {
    cpSync(resolve(shared, 'references', file), resolve(target, 'references', file));
  }
  const examples = resolve(source, 'examples');
  checkExamples(skill, examples);
  if (existsSync(examples)) cpSync(examples, resolve(target, 'examples'), { recursive: true });

  for (const path of bundledPaths(text)) {
    if (!existsSync(resolve(target, path))) {
      throw new Error(`${skill.name}: SKILL.md points at ${path}, which the skill does not ship`);
    }
  }
}

/**
 * Builds every skill from `skills/`: one folder and one zip per skill, the installer and the kit.
 * The output folder has the kit's layout, so its `install.mjs` works from there too.
 */
export async function buildSkills(out: string = DEFAULT_OUT): Promise<void> {
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const validator = await bundleScript('validate-cli.ts');
  for (const skill of SKILLS) buildSkill(skill, out, validator);
  writeFileSync(resolve(out, 'install.mjs'), await bundleScript('install-cli.ts'));
  cpSync(resolve(SOURCES, 'shared/kit'), out, { recursive: true });

  for (const { name } of SKILLS) {
    const dir = resolve(out, name);
    const files = listFiles(dir).map((file) => ({ name: `${name}/${file}`, path: resolve(dir, file) }));
    writeFileSync(resolve(out, `${name}.zip`), zipFiles(files));
  }
  const kit = listFiles(out).map((file) => ({ name: `${KIT_NAME}/${file}`, path: resolve(out, file) }));
  writeFileSync(resolve(out, `${KIT_NAME}.zip`), zipFiles(kit));
}
